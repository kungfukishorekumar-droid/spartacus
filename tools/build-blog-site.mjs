/* ============================================================
   Builds dist-blog/ — everything that gets deployed to
   blog.spartacusmartialarts.com

   Run:  node tools/build-blog-site.mjs

   The blog host serves ONLY the blog. Links to Programs / About /
   Contact are rewritten to the main domain at runtime by site-base.js,
   so there is no duplicated content between the two hosts.
   ============================================================ */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "dist-blog");
const BLOG = "https://blog.spartacusmartialarts.com";
const MAIN = "https://spartacusmartialarts.com";

const FILES = [
  "blog.html", "blog-post.html",
  "site-base.js", "app.js", "analytics.js", "track.js",
  "blog.js", "blog-lead.js", "ux.js", "fx.js",
  "styles.css", "blog.css", "ux.css", "fx.css",
  "content.json", "llms.txt"
];
const DIRS = ["data", "fonts", "assets", "images"];

/* ---------- helpers ---------- */
function rmrf(p) { fs.rmSync(p, { recursive: true, force: true }); }
function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

/* ---------- read every post by executing the data files ---------- */
function loadPosts() {
  const win = { BLOG_POSTS: [], BLOG_CATEGORIES: [] };
  const sandbox = { window: win, document: { createElement: () => ({}) }, encodeURIComponent };
  const dataFiles = fs.readdirSync(path.join(ROOT, "data"))
    .filter(f => f.endsWith(".js"))
    .sort((a, b) => (a === "blogData.js" ? -1 : b === "blogData.js" ? 1 : a.localeCompare(b)));
  for (const f of dataFiles) {
    const code = fs.readFileSync(path.join(ROOT, "data", f), "utf8");
    // eslint-disable-next-line no-new-func
    new Function("window", "document", "encodeURIComponent", code)(
      sandbox.window, sandbox.document, sandbox.encodeURIComponent
    );
  }
  return win.BLOG_POSTS;
}

/* ---------- build ---------- */
rmrf(OUT);
fs.mkdirSync(OUT, { recursive: true });

for (const f of FILES) {
  if (fs.existsSync(path.join(ROOT, f))) fs.copyFileSync(path.join(ROOT, f), path.join(OUT, f));
  else console.warn("  ! missing:", f);
}
for (const d of DIRS) {
  if (fs.existsSync(path.join(ROOT, d))) copyDir(path.join(ROOT, d), path.join(OUT, d));
}

/* blog.html ships a hard-coded canonical for the main domain — repoint it */
{
  const p = path.join(OUT, "blog.html");
  let html = fs.readFileSync(p, "utf8");
  html = html.replaceAll(`${MAIN}/blog.html`, `${BLOG}/blog.html`);
  html = html.replace(
    '<meta property="og:type" content="website" />',
    `<meta property="og:type" content="website" />\n<meta property="og:url" content="${BLOG}/blog.html" />`
  );
  fs.writeFileSync(p, html);
}

/* ---------- sitemap: every article, on the blog host ---------- */
const posts = loadPosts();
posts.sort((a, b) => new Date(b.publishedDate) - new Date(a.publishedDate));
const newest = posts[0]?.publishedDate || new Date().toISOString().slice(0, 10);

const urls = [
  `  <url><loc>${BLOG}/blog.html</loc><lastmod>${newest}</lastmod><changefreq>weekly</changefreq><priority>0.9</priority></url>`,
  ...posts.map(p =>
    `  <url><loc>${BLOG}/blog-post.html?slug=${p.slug}</loc><lastmod>${p.publishedDate}</lastmod><priority>0.7</priority></url>`)
];
fs.writeFileSync(path.join(OUT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`);

